"""Writes asset-library/CREDITS.md and manifest.json (beside asset-library/) from what is actually in the library.

Run: python -I Scripts/make_credits.py <project_root>
"""
import json
import os
import sys

ROOT = os.path.abspath(sys.argv[1] if len(sys.argv) > 1 else ".")
LIB = os.path.join(ROOT, "asset-library")

rec_path = os.path.join(LIB, "polyhaven_records.json")
with open(rec_path, encoding="utf-8-sig") as f:
    ph = json.load(f)
ph = [r for r in ph if os.path.isdir(os.path.join(ROOT, r["path"]))]

manifest = []
for r in ph:
    manifest.append({"path": r["path"], "source_name": r["source_name"], "source_url": r["source_url"], "license": "CC0-1.0", "author": r["author"]})
fonts = [
    ("asset-library/Fonts/lobster", "Lobster by Pablo Impallari (Google Fonts)", "https://github.com/google/fonts/tree/main/ofl/lobster"),
    ("asset-library/Fonts/kalam", "Kalam by Indian Type Foundry (Google Fonts)", "https://github.com/google/fonts/tree/main/ofl/kalam"),
    ("asset-library/Fonts/lato", "Lato by Łukasz Dziedzic (Google Fonts)", "https://github.com/google/fonts/tree/main/ofl/lato"),
    ("asset-library/Fonts/cormorantgaramond", "Cormorant Garamond by Christian Thalmann (Google Fonts)",
     "https://github.com/google/fonts/tree/main/ofl/cormorantgaramond"),
]
fonts = [f for f in fonts if os.path.isdir(os.path.join(ROOT, f[0]))]
for path, name, url in fonts:
    manifest.append({"path": path, "source_name": name, "source_url": url, "license": "OFL-1.1", "author": name.split(" by ")[1].split(" (")[0]})
generated = [
    ("asset-library/Audio/generated", "Original music, ambience and SFX synthesised by Scripts/gen_audio.py"),
    ("asset-library/Textures/generated", "Original procedural textures generated by Scripts/gen_textures.py"),
    ("asset-library/Models/generated", "Original cat model (SDF sculpt Scripts/blender/cat_sdf.py -> Scripts/blender/make_cat.py: ears, eyes, whiskers, fur shells, 35-bone skeleton)"),
    ("asset-library/Models/generated/ue_export", "FBX export of every mesh made or edited in the editor, as the game shows it: the village (houses, "
     "bridge, paving, plinth, sills, window boxes, washing line...) built by Scripts/unreal/sns_*.py with GeometryScript, and the "
     "Poly Haven props as split/fitted there (their CC0 originals are in Models/polyhaven). Index: asset-library/SOURCES.csv"),
]
generated = [g for g in generated if os.path.isdir(os.path.join(ROOT, g[0]))]
for path, name in generated:
    manifest.append({"path": path, "source_name": name, "source_url": "this project", "license": "Original work (CC0-1.0 dedication)", "author": "Shade and Seek team"})

# Later additions are logged as fragments next to what they describe (fetch/sourcing scripts write them).
FRAGMENTS = ["asset-library/manifest_assets_new.json", "asset-library/Audio/manifest_audio.json", "asset-library/Fonts/manifest_fonts_new.json"]
known = {e["path"] for e in manifest}
extra = []
for frag in FRAGMENTS:
    fp = os.path.join(ROOT, frag)
    if os.path.exists(fp):
        with open(fp, encoding="utf-8-sig") as f:
            for e in json.load(f):
                if e["path"] not in known and os.path.exists(os.path.join(ROOT, e["path"])):
                    known.add(e["path"])
                    extra.append(e)
manifest += extra
ph += [{"path": e["path"], "author": e["author"], "source_url": e["source_url"]} for e in extra if "polyhaven.com" in e["source_url"]]
acg = [e for e in extra if "ambientcg.com" in e["source_url"]]
audio = [e for e in extra if e["path"].startswith("asset-library/Audio/")]
new_fonts = [e for e in extra if e["path"].startswith("asset-library/Fonts/")]
other = [e for e in extra if "polyhaven.com" not in e["source_url"] and e not in acg and e not in audio and e not in new_fonts]

with open(os.path.join(ROOT, "manifest.json"), "w", encoding="utf-8") as f:
    json.dump(manifest, f, indent=2, ensure_ascii=False)

lines = ["# Shade and Seek - asset credits", "",
         "Every third-party asset is free, redistributable in source form, and carries no AI-training restriction.",
         "No Fab / Unreal Marketplace / Megascans content is used. Engine content is only used as C++ fallbacks.", "",
         "## Original (made for this project)", ""]
for path, name in generated:
    lines.append(f"- `{path}` - {name}")
lines += ["", "## Fonts (SIL Open Font License 1.1, licence text included next to each font)", ""]
for path, name, url in fonts:
    lines.append(f"- `{path}` - {name} - {url}")
for e in new_fonts:
    lines.append(f"- `{e['path']}` - {e['source_name'].replace('Google Fonts - ', '')} by {e['author']} (Google Fonts) - {e['source_url']}")
lines.append("- Fraunces and Nunito ship as variable fonts; `Scripts/fetch_fonts.py` bakes the static weights in their `static/` folders (fontTools instancer).")
lines += ["", "## Poly Haven (CC0 1.0 - public domain, https://polyhaven.com/license)", "", "| Asset | Author(s) | Source |", "|---|---|---|"]
for r in sorted(ph, key=lambda r: r["path"]):
    lines.append(f"| `{r['path'].replace('asset-library/', '')}` | {r['author']} | {r['source_url']} |")
if acg:
    lines += ["", "## ambientCG (CC0 1.0 - public domain, https://docs.ambientcg.com/license/)", "", "| Asset | Author(s) | Source |", "|---|---|---|"]
    for e in sorted(acg, key=lambda e: e["path"]):
        lines.append(f"| `{e['path'].replace('asset-library/', '')}` | {e['author']} | {e['source_url']} |")
if audio:
    lines += ["", "## Audio (CC0 1.0, Public Domain Mark 1.0, CC BY 4.0 - see each row)", "",
              "Game-ready files are built from these by `Scripts/prep_audio.py` into `asset-library/Audio/game`. Freesound files are the",
              "public HQ previews of CC0 originals; the Radio Aporee field recordings (mirrored on Internet Archive) are stored as",
              "lossless excerpts. CC BY 4.0 music must be credited wherever the game or a video of it is published:",
              "\"Home Was You\" by Scott Buckley (www.scottbuckley.com.au), licensed under CC BY 4.0.", "",
              "| File | Title | Author | Licence | Source |", "|---|---|---|---|---|"]
    for e in sorted(audio, key=lambda e: e["path"]):
        lines.append(f"| `{e['path'].replace('asset-library/', '')}` | {e['source_name']} | {e['author']} | {e['license']} | {e['source_url']} |")
if other:
    lines += ["", "## Other (CC0 1.0 - public domain)", "", "| Asset | Author(s) | Source |", "|---|---|---|"]
    for e in sorted(other, key=lambda e: e["path"]):
        lines.append(f"| `{e['path'].replace('asset-library/', '')}` | {e['author']} | {e['source_url']} |")
lines.append("")
lines.append("Note: `Textures/polyhaven/fabric_pattern_07/fabric_pattern_07_diff_1k.jpg` is Poly Haven's `col_1` colourway, renamed.")
with open(os.path.join(LIB, "CREDITS.md"), "w", encoding="utf-8") as f:
    f.write("\n".join(lines) + "\n")
print("credits:", len(manifest), "entries")
